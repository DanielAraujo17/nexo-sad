-- Esquema lógico da tabela única do Nexo.
-- Na execução normal, SQLAlchemy cria esta estrutura automaticamente.

CREATE TABLE IF NOT EXISTS chamados (
    id_chamado INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(180) NOT NULL,
    categoria VARCHAR(40) NOT NULL,
    urgencia VARCHAR(20) NOT NULL,
    usuarios_afetados INTEGER NOT NULL CHECK (usuarios_afetados >= 1),
    criticidade INTEGER NOT NULL CHECK (criticidade BETWEEN 1 AND 5),
    idade_horas DOUBLE PRECISION NOT NULL DEFAULT 0,
    recorrencias INTEGER NOT NULL DEFAULT 0,
    complexidade VARCHAR(20) NOT NULL,
    tempo_resolucao_horas DOUBLE PRECISION NULL,
    violou_sla INTEGER NULL CHECK (violou_sla IN (0, 1)),
    status VARCHAR(12) NOT NULL CHECK (status IN ('aberto', 'resolvido')),
    aberto_em TIMESTAMPTZ NOT NULL,
    resolvido_em TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS ix_chamados_status ON chamados (status);
CREATE INDEX IF NOT EXISTS ix_chamados_aberto_em ON chamados (aberto_em);
CREATE INDEX IF NOT EXISTS ix_chamados_resolvido_em ON chamados (resolvido_em);
